<#
.SYNOPSIS
  Copy the harness scripts that must run outside a repo, and regenerate their
  hash manifest. Verifies every copy.

.DESCRIPTION
  WHY ANYTHING IS DEPLOYED AT ALL
  -------------------------------
  Scheduled tasks point at these files. Infrastructure that keeps a mind reachable
  must not depend on the state of a git checkout -- a pull, a reset, or a bad merge
  should not be able to break the thing that notices the machine has gone dark.
  That is the same reason the heartbeat lives at D:\Lupo\lodestone-heartbeat\,
  outside every repo.

  WHY THIS SCRIPT EXISTS, RATHER THAN A COPY BY HAND
  -------------------------------------------------
  The cost of deploying outside the repo is DRIFT. ops/heartbeat.ps1 sat one patch
  behind its live copy for days with no way to notice.

  So a manifest records the source hashes. And then, on 2026-09-26, an audit found
  that the manifest ITSELF had drifted: the hashes were current but its "Deployed:"
  date still read the previous day, because it was maintained by hand with a regex.
  A drift detector maintained by the process it is meant to catch is not a drift
  detector.

  Hence this file. The manifest is GENERATED, never edited. Run this after any
  change to a deployed script, and run `-Verify` any time you want to know whether
  the running copies still match source.

.PARAMETER Verify
  Check only. Reports drift and exits 1 if any deployed file differs from source.
  Changes nothing. Safe to run from a scheduled task.

.OUTPUTS
  Exit 0 = deployed (or verified clean). Exit 1 = drift found in -Verify mode.
  Exit 2 = a copy could not be verified; nothing was trusted.

.NOTES
  Author: Lodestone <lodestone@smoothcurves.nexus>
  Collaborator: Lupo
#>

[CmdletBinding()]
param(
    [string] $BinDir = 'D:\Lupo\hacs-runtime\bin',
    [switch] $Verify
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# Only scripts a SCHEDULED TASK invokes belong here. Everything else is run from
# the repo, where it should be, so this list stays short on purpose.
$deployed = @(
    'credential-sentinel.ps1',
    'run-hidden.vbs'
)

$rows = @()
$drift = @()

foreach ($f in $deployed) {
    $src = Join-Path $PSScriptRoot $f
    $dst = Join-Path $BinDir $f
    if (-not (Test-Path $src)) { Write-Error "source missing: $src"; exit 2 }

    $srcHash = (Get-FileHash $src -Algorithm SHA256).Hash.ToLower()

    if ($Verify) {
        if (-not (Test-Path $dst)) { $drift += "$f : NOT DEPLOYED"; continue }
        $dstHash = (Get-FileHash $dst -Algorithm SHA256).Hash.ToLower()
        if ($dstHash -ne $srcHash) { $drift += "$f : deployed copy differs from source" }
        $rows += "$srcHash  $f"
        continue
    }

    $null = New-Item -ItemType Directory -Force -Path $BinDir -ErrorAction SilentlyContinue
    Copy-Item $src $dst -Force
    $dstHash = (Get-FileHash $dst -Algorithm SHA256).Hash.ToLower()
    if ($dstHash -ne $srcHash) {
        # Never report a deploy that did not verify. That is the whole point.
        Write-Error "DEPLOY FAILED for ${f}: source $srcHash but copy $dstHash"
        exit 2
    }
    Write-Host ("  {0,-26} VERIFIED  {1}" -f $f, $srcHash.Substring(0, 16)) -ForegroundColor Green
    $rows += "$srcHash  $f"
}

if ($Verify) {
    if ($drift.Count -gt 0) {
        Write-Host "DRIFT:" -ForegroundColor Red
        $drift | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
        exit 1
    }
    Write-Host "no drift: every deployed copy matches source" -ForegroundColor Green
    exit 0
}

# --- the manifest is GENERATED, never hand-edited -------------------------------
$lines = @(
    '# Deployed copies -- GENERATED BY deploy.ps1. DO NOT EDIT, AND DO NOT EDIT THE COPIES.'
    ''
    "Canonical source : $PSScriptRoot"
    "Deployed at      : $((Get-Date).ToString('o'))"
    "Deployed by      : deploy.ps1 on $env:COMPUTERNAME"
    ''
    'These run from OUTSIDE every git repo on purpose. A pull, a reset or a bad merge'
    'must not be able to break the thing that notices this machine has gone dark.'
    ''
    'The cost of that choice is drift, and ops/heartbeat.ps1 once sat one patch behind'
    'its live copy for days with nobody able to tell. So this manifest records source'
    'hashes -- and an audit on 2026-09-26 found the MANIFEST had drifted too, because'
    'it was maintained by hand: the hashes were right and the date was a day stale.'
    'A drift detector maintained by the process it is meant to catch is not a drift'
    'detector. Hence deploy.ps1.'
    ''
    'To check: deploy.ps1 -Verify   (exit 1 on drift, changes nothing)'
    ''
    '## SHA-256 of source at deploy time'
    ''
) + $rows

Set-Content -Path (Join-Path $BinDir 'DEPLOYED.md') -Value $lines -Encoding utf8
Write-Host "manifest regenerated: $(Join-Path $BinDir 'DEPLOYED.md')"
exit 0
